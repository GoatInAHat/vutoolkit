#!/usr/bin/env node
// Generates src/owa/catalog.generated.ts, the OWA action catalog, from Microsoft's published
// Exchange Web Services schema: the MS-OXWS* protocol schemas Microsoft ships in
// OfficeDev/Interop-TestSuites (MIT), pinned to one commit. Nothing in the catalog is hand-written:
// every operation is a request element whose type derives from m:BaseRequestType, and every type
// is the schema's own. Run it again to move to a newer schema commit:
//
//   node scripts/owa-catalog.mjs                 # fetch the pinned commit's schema files
//   node scripts/owa-catalog.mjs --dir <path>    # or read a local copy of SchemaValidation/
//                                --docs <path>   # and of the reference's web-service-reference/
//
// The parsing and catalog building live in src/owa/xsd.ts (unit-tested); this script only fetches
// the files and writes the module.
import { mkdirSync, readFileSync, readdirSync, writeFileSync } from "node:fs";
import { join } from "node:path";
import { fileURLToPath, pathToFileURL } from "node:url";

const REPO = "OfficeDev/Interop-TestSuites";
const COMMIT = "fe87ed3253de01804a2ae6e1d0015943da6023f8";
const DIR = "ExchangeWebServices/Source/Common/SchemaValidation";
// Microsoft's EWS reference (CC BY 4.0) lists every operation, including the ones the protocol
// schemas above leave out (Inbox rules, out-of-office, availability, mail tips ...).
const DOCS_REPO = "MicrosoftDocs/office-developer-exchange-docs";
const DOCS_COMMIT = "1decceff40902e1381fe761119f3d891570b1f14";
const DOCS_DIR = "docs/web-service-reference";
const DOCS_BASE = "https://learn.microsoft.com/en-us/exchange/client-developer/web-service-reference";
const root = fileURLToPath(new URL("../", import.meta.url));

const args = process.argv.slice(2);
const local = args.includes("--dir") ? args[args.indexOf("--dir") + 1] : undefined;
const localDocs = args.includes("--docs") ? args[args.indexOf("--docs") + 1] : undefined;

async function schemaFiles() {
  if (local) {
    return readdirSync(local).filter((f) => f.endsWith(".xsd")).sort().map((name) => ({ name, text: readFileSync(join(local, name), "utf8") }));
  }
  const listing = await fetch(`https://api.github.com/repos/${REPO}/contents/${DIR}?ref=${COMMIT}`, {
    headers: { accept: "application/vnd.github+json", "user-agent": "vutoolkit-owa-catalog" },
  });
  if (!listing.ok) throw new Error(`could not list ${REPO}/${DIR}: HTTP ${listing.status}`);
  const names = (await listing.json()).map((e) => e.name).filter((n) => n.endsWith(".xsd")).sort();
  const files = [];
  for (const name of names) {
    const res = await fetch(`https://raw.githubusercontent.com/${REPO}/${COMMIT}/${DIR}/${name}`);
    if (!res.ok) throw new Error(`could not fetch ${name}: HTTP ${res.status}`);
    files.push({ name, text: await res.text() });
  }
  return files;
}

async function docsPages() {
  const read = localDocs
    ? async (name) => { try { return readFileSync(join(localDocs, name), "utf8"); } catch { return undefined; } }
    : async (name) => {
        const res = await fetch(`https://raw.githubusercontent.com/${DOCS_REPO}/${DOCS_COMMIT}/${DOCS_DIR}/${name}`);
        return res.ok ? res.text() : undefined;
      };
  const index = await read("ews-operations-in-exchange.md");
  if (!index) throw new Error("could not read the EWS reference's operation list");
  const pages = {};
  for (const [, file] of index.matchAll(/\]\(([a-z0-9-]+-operation\.md)\)/g)) {
    if (!(file in pages)) pages[file] = await read(file);
  }
  return { index, pages };
}

const { buildCatalog, documentedOperations } = await import(pathToFileURL(join(root, "dist/owa/xsd.js")).href);
const files = await schemaFiles();
const catalog = buildCatalog(files, { repo: REPO, commit: COMMIT, path: DIR });
const docs = await docsPages();
catalog.documented = documentedOperations(docs.index, docs.pages, DOCS_BASE);
catalog.source.docs = { repo: DOCS_REPO, commit: DOCS_COMMIT, path: DOCS_DIR, pages: Object.values(docs.pages).filter(Boolean).length };
const out = join(root, "src/owa/catalog.generated.ts");
mkdirSync(join(root, "src/owa"), { recursive: true });
writeFileSync(
  out,
  "// Generated by scripts/owa-catalog.mjs from Microsoft's published EWS schema and reference. Do not edit.\n" +
    `// Sources: https://github.com/${REPO}/tree/${COMMIT}/${DIR} (MIT)\n` +
    `//          https://github.com/${DOCS_REPO}/tree/${DOCS_COMMIT}/${DOCS_DIR} (CC BY 4.0)\n` +
    'import type { Catalog } from "./xsd.js";\n\n' +
    `export const catalog: Catalog = JSON.parse(${JSON.stringify(JSON.stringify(catalog))});\n`,
);
console.error(`owa catalog: ${Object.keys(catalog.operations).length} schema operations, ${Object.keys(catalog.types).length} types from ${files.length} schema files; ${Object.keys(catalog.documented).length} documented operations -> ${out}`);
